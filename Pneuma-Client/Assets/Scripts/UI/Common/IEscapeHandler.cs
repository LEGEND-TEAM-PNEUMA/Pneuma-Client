namespace Pneuma.UI.Common
{
    // ESC / 뒤로가기 입력을 받을 수 있는 대상입니다. (UI 기획서 2.1)
    //
    // 기획서의 ESC 규칙은 화면마다 동작이 다릅니다.
    //   - 상위 화면 복귀 (캐릭터 선택, 사전 계열)
    //   - 오버레이만 닫기 (설정, 카드 목록)
    //   - 다른 화면 호출  (전투 → 일시정지 메뉴)
    //   - 아예 막기       (로고 스플래시, 로딩, 카드 보상)
    //   - 확인창 띄우기   (로비 → 종료 확인)
    //
    // 그래서 라우터가 동작을 정하지 않고, 화면이 자기 동작을 직접 구현합니다.
    // 라우터는 "지금 맨 위에 있는 대상"에게 넘기는 일만 합니다.
    public interface IEscapeHandler
    {
        /// <summary>
        /// ESC 입력을 처리합니다.
        /// </summary>
        /// <returns>
        /// 입력을 소비했으면 true. 이 경우 아래 대상에게 전달되지 않습니다.
        /// ESC를 막아야 하는 화면(카드 보상 등)도 아무 일도 하지 않고 true를 반환하면 됩니다.
        /// false를 반환하면 스택 아래 대상이 대신 처리합니다.
        /// </returns>
        bool HandleEscape();
    }
}
